import type { PrismaClient } from '@prisma/client'
import type { Redis } from 'ioredis'
import type { VehicleDetailDTO, VehicleListItemDTO, SubscriptionTier } from '@decar/shared'

const CACHE_TTL = 3600 // 1 hour

type VehicleWithRelations = Awaited<ReturnType<typeof queryVehicle>>

async function queryVehicle(prisma: PrismaClient, id: string) {
  return prisma.vehicle.findUnique({
    where: { id },
    include: {
      engine: true,
      exterior: { include: { colors: true } },
      interior: true,
      media: { orderBy: { sortOrder: 'asc' } },
    },
  })
}

function applyTierMask(vehicle: NonNullable<VehicleWithRelations>, tier: SubscriptionTier): VehicleDetailDTO {
  const isPro = tier === 'PRO'

  return {
    id: vehicle.id,
    slug: vehicle.slug,
    make: vehicle.make,
    model: vehicle.model,
    year: vehicle.year,
    market: vehicle.market,
    trimLevel: vehicle.trimLevel,
    engine: vehicle.engine
      ? {
          displacement: vehicle.engine.displacement,
          cylinders: vehicle.engine.cylinders,
          fuelType: vehicle.engine.fuelType as VehicleDetailDTO['engine'] extends null ? never : NonNullable<VehicleDetailDTO['engine']>['fuelType'],
          powerKw: isPro ? vehicle.engine.powerKw : 0,
          torqueNm: isPro ? vehicle.engine.torqueNm : 0,
          transmission: isPro ? vehicle.engine.transmission : 'Upgrade to Pro',
          drivetrain: vehicle.engine.drivetrain,
        }
      : null,
    exterior: vehicle.exterior
      ? {
          bodyType: vehicle.exterior.bodyType,
          lengthMm: isPro ? vehicle.exterior.lengthMm : 0,
          widthMm: isPro ? vehicle.exterior.widthMm : 0,
          heightMm: isPro ? vehicle.exterior.heightMm : 0,
          wheelbaseMm: isPro ? vehicle.exterior.wheelbaseMm : 0,
          colors: vehicle.exterior.colors.map((c) => ({
            id: c.id,
            name: c.name,
            hexCode: c.hexCode,
            isPrimary: c.isPrimary,
          })),
        }
      : null,
    interior: isPro && vehicle.interior
      ? {
          seatMaterial: vehicle.interior.seatMaterial,
          seatRows: vehicle.interior.seatRows,
          seatCount: vehicle.interior.seatCount,
          dashboard: vehicle.interior.dashboard,
          techFeatures: vehicle.interior.techFeatures,
        }
      : null,
    media: vehicle.media
      .filter((m) => isPro || !m.isPro)
      .map((m) => ({
        id: m.id,
        type: m.type as VehicleDetailDTO['media'][number]['type'],
        isPro: m.isPro,
        sortOrder: m.sortOrder,
      })),
  }
}

export async function getVehicle(
  prisma: PrismaClient,
  redis: Redis,
  id: string,
  tier: SubscriptionTier,
): Promise<VehicleDetailDTO | null> {
  const cacheKey = `vehicle:${id}`
  const cached = await redis.get(cacheKey)

  let raw: NonNullable<VehicleWithRelations> | null

  if (cached) {
    raw = JSON.parse(cached) as NonNullable<VehicleWithRelations>
  } else {
    raw = await queryVehicle(prisma, id)
    if (!raw) return null
    await redis.setex(cacheKey, CACHE_TTL, JSON.stringify(raw))
  }

  if (!raw) return null
  return applyTierMask(raw, tier)
}

export async function invalidateVehicleCache(redis: Redis, id: string): Promise<void> {
  await redis.del(`vehicle:${id}`)
}

export async function listVehicles(
  prisma: PrismaClient,
  page: number,
  limit: number,
): Promise<{ data: VehicleListItemDTO[]; total: number }> {
  const skip = (page - 1) * limit

  const [vehicles, total] = await Promise.all([
    prisma.vehicle.findMany({
      skip,
      take: limit,
      include: {
        exterior: { select: { bodyType: true } },
        media: {
          where: { type: 'EXTERIOR_IMAGE', isPro: false },
          orderBy: { sortOrder: 'asc' },
          take: 1,
        },
      },
      orderBy: [{ make: 'asc' }, { model: 'asc' }, { year: 'desc' }],
    }),
    prisma.vehicle.count(),
  ])

  return {
    data: vehicles.map((v) => ({
      id: v.id,
      slug: v.slug,
      make: v.make,
      model: v.model,
      year: v.year,
      market: v.market,
      trimLevel: v.trimLevel,
      bodyType: v.exterior?.bodyType ?? null,
      thumbnailUrl: null, // signed URL is generated by media service at request time
    })),
    total,
  }
}
